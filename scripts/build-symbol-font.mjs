// 로고 기호용 글꼴 부분집합을 만들어 src/config/symbolFont.generated.ts 로 굳힌다.
//
// 왜 필요한가. 브랜드 글꼴(Instrument Serif 등 본문용 세리프)에는 ✦ 같은 기호가 없다 —
// 원본 TTF 를 열어 봐도 글리프 인덱스가 0(.notdef)이다. 그래서 사이트 로고도 탭 아이콘도
// 기기에 깔린 대체 글꼴이 그리고 있었고, 고르는 맥락이 달라 둘이 서로 다르게 나왔다(#1048).
//
// 기호를 담당할 글꼴(Noto Sans Symbols 2, OFL)에서 쓸 만한 기호만 추려 굳혀 두고,
// 서버는 여기서 외곽선을 뽑아 favicon 에 넣고, 페이지는 같은 파일을 @font-face 로 얹는다.
// 원본은 1.2MB 라 통째로 들일 수 없고, 서버리스 런타임은 레포 파일시스템을 못 읽으므로
// localFonts.generated.ts 와 같이 빌드타임 모듈로 굳힌다.
//
// 사용: `node scripts/build-symbol-font.mjs [원본.ttf]`
//   인자를 안 주면 Google Fonts 저장소에서 받아 온다(네트워크 필요).
//   결과물은 커밋되므로 평소 빌드는 이 스크립트를 돌리지 않는다.
import { writeFileSync, readFileSync, existsSync } from "node:fs";
import { join } from "node:path";
import opentypeCjs from "opentype.js";

/* CJS 패키지라 네임스페이스가 아니라 default 안에 들어온다 */
const opentype = opentypeCjs;

const SOURCE_URL =
  "https://raw.githubusercontent.com/google/fonts/main/ofl/notosanssymbols2/NotoSansSymbols2-Regular.ttf";
const OUT = join(process.cwd(), "src", "config", "symbolFont.generated.ts");

/* 로고 마크로 쓸 만한 기호만. 늘리면 그만큼 파일이 커지므로(9자에 2.6KB) 필요할 때 추가한다.
   영문·숫자는 넣지 않는다 — 워드마크는 브랜드 글꼴이 그대로 맡아야 한다. */
const CHARS = [
  ..."✦✧✩✪✫✬✭✮✯✰★☆✶✷✸✹✺✳✴❂❉❊❋",
  ..."◆◇◈❖●○◉◎◍■□▪▫▲△▼▽◀▶◤◥",
  ..."✕✖✗✘✚✜✛❯❮➔➜➙⟶⟵",
  ..."⬢⬡⬣⭑⭒⬤⬥⬦⬧",
  ..."✿❀❁❃☘☙☾☽⚡⚘✱✲✽✾❄❅❆",
];

const sourcePath = process.argv[2];
let buf;
if (sourcePath && existsSync(sourcePath)) {
  buf = readFileSync(sourcePath);
} else {
  const res = await fetch(SOURCE_URL);
  if (!res.ok) {
    console.error(`원본 글꼴을 받지 못했습니다 (${res.status}). 파일을 직접 받아 경로를 인자로 주세요.`);
    process.exit(1);
  }
  buf = Buffer.from(await res.arrayBuffer());
}

const src = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));

/* .notdef 는 첫 글리프여야 한다(글꼴 규격). 없는 글자는 조용히 건너뛴다 —
   원본이 바뀌어 빠진 기호가 생겨도 빌드는 계속되고, 그 글자는 예전처럼 <text> 로 떨어진다. */
const glyphs = [
  new opentype.Glyph({
    name: ".notdef",
    unicode: 0,
    advanceWidth: Math.round(src.unitsPerEm / 2),
    path: new opentype.Path(),
  }),
];
const missing = [];
for (const ch of CHARS) {
  const g = src.charToGlyph(ch);
  if (g.index === 0) {
    missing.push(ch);
    continue;
  }
  glyphs.push(
    new opentype.Glyph({
      name: g.name,
      unicode: ch.codePointAt(0),
      advanceWidth: g.advanceWidth,
      path: g.path,
    }),
  );
}

const font = new opentype.Font({
  familyName: "Brand Symbols",
  styleName: "Regular",
  unitsPerEm: src.unitsPerEm,
  ascender: src.ascender,
  descender: src.descender,
  glyphs,
});

const bytes = Buffer.from(font.toArrayBuffer());
const codepoints = glyphs.slice(1).map((g) => g.unicode).sort((a, b) => a - b);

/* @font-face 의 unicode-range — 여기 없는 글자는 브라우저가 이 글꼴을 아예 안 받는다.
   영문만 쓰는 화면에서 공짜로 넘어가게 하려는 것이다. 이어지는 코드포인트는 구간으로 묶는다. */
const ranges = [];
for (const cp of codepoints) {
  const last = ranges[ranges.length - 1];
  if (last && cp === last[1] + 1) last[1] = cp;
  else ranges.push([cp, cp]);
}
const unicodeRange = ranges
  .map(([a, b]) => (a === b ? `U+${a.toString(16).toUpperCase()}` : `U+${a.toString(16).toUpperCase()}-${b.toString(16).toUpperCase()}`))
  .join(", ");

writeFileSync(
  OUT,
  `// AUTO-GENERATED by scripts/build-symbol-font.mjs — 편집하지 마세요.
// 로고 기호용 글꼴(Noto Sans Symbols 2, OFL) 부분집합. 재생성: node scripts/build-symbol-font.mjs
/** 부분집합 글꼴 바이트 (base64, OTF) */
export const SYMBOL_FONT_BASE64 = ${JSON.stringify(bytes.toString("base64"))};
/** 페이지 @font-face 가 쓰는 이름 — favicon 이 뽑는 외곽선과 같은 글꼴이다 */
export const SYMBOL_FONT_FAMILY = "Brand Symbols";
/** 이 글꼴이 담고 있는 글자 범위 */
export const SYMBOL_FONT_UNICODE_RANGE = ${JSON.stringify(unicodeRange)};
`,
  "utf8",
);

console.log(`🔣 기호 글꼴 — ${glyphs.length - 1}자, ${(bytes.length / 1024).toFixed(1)} KiB → ${OUT}`);
if (missing.length) console.log(`   원본에 없어 건너뜀: ${missing.join(" ")}`);
