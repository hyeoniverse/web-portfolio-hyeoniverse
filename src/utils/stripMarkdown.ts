/**
 * 마크다운 원문 → 평문. **미리보기 전용** (렌더가 아니라 기호를 벗겨 텍스트만 남긴다).
 *
 * 쓰는 곳: 목록/사이드바처럼 몇 줄로 잘라 보여주는 자리.
 * 그런 자리엔 제목·목록·코드블록·표를 렌더할 공간이 없어서, 렌더하면 오히려 깨진다.
 * → 기호만 제거해 한 줄짜리 텍스트로 만든다.
 *
 * 대응 범위는 댓글 마크다운이 실제로 허용하는 문법에 맞춤
 * (CommentMarkdown 의 ALLOWED_TAGS: 헤딩·강조·코드·인용·목록·체크박스·링크·이미지·표·hr·br).
 */
export function stripMarkdown(md: string): string {
  return (
    md
      // 코드펜스 — 내용까지 통째로 제거. 미리보기에 코드 덩어리는 의미 없고 줄만 잡아먹는다
      .replace(/```[\s\S]*?```/g, " ")
      // 이미지 — alt 까지 버림 (미리보기에 "이미지 설명"만 남으면 문맥이 이상해짐). 링크보다 먼저 처리
      .replace(/!\[[^\]]*\]\([^)]*\)/g, " ")
      // 링크 — 표시 텍스트만 남기고 URL 제거
      .replace(/\[([^\]]*)\]\([^)]*\)/g, "$1")
      // 인라인 코드
      .replace(/`([^`]+)`/g, "$1")
      // 강조 — **bold** / __bold__ 를 *it* / _it_ 보다 먼저 (겹침 방지)
      .replace(/\*\*([^*]+)\*\*/g, "$1")
      .replace(/__([^_]+)__/g, "$1")
      .replace(/~~([^~]+)~~/g, "$1")
      .replace(/\*([^*\n]+)\*/g, "$1")
      // _it_ 은 단어 경계에서만 — snake_case 식별자가 망가지지 않도록
      .replace(/(^|\s)_([^_\n]+)_(?=\s|$)/g, "$1$2")
      // 줄 시작 마커 — 헤딩 / 인용 / 목록(체크박스 포함) / 번호목록
      .replace(/^\s{0,3}(#{1,6}\s+|>\s?|[-*+]\s+(\[[ xX]\]\s+)?|\d+[.)]\s+)/gm, "")
      // 수평선
      .replace(/^\s*([-*_]\s*){3,}$/gm, " ")
      // 표 구분행(|---|:--:|) 제거 후, 남은 파이프는 공백으로
      .replace(/^\s*\|?[\s:|-]*-[\s:|-]*\|[\s:|-]*$/gm, " ")
      .replace(/\|/g, " ")
      // 허용 태그로 직접 쓴 HTML (<br/> 등)
      .replace(/<[^>]*>/g, " ")
      // 개행 포함 모든 공백을 한 칸으로 — 몇 줄로 잘릴 자리라 줄바꿈이 의미 없다
      .replace(/\s+/g, " ")
      .trim()
  );
}
