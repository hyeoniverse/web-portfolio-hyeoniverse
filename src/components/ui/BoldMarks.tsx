/* --------------------------------------------------------------------------
   BoldMarks — 번역 문구 안의 <b>…</b> 를 굵게 그린다.

   확인 문구처럼 문장 가운데 개수나 파일 이름을 강조할 때 쓴다. 강조할 자리를 문구에
   <b> 로 표시해 두면 언어마다 어순이 달라도 강조가 따라간다. 그 밖의 태그는 글자 그대로 둔다.
   -------------------------------------------------------------------------- */

export default function BoldMarks({ text }: { text: string }) {
  return <>{text.split(/<b>(.*?)<\/b>/).map((part, i) => (i % 2 ? <strong key={i}>{part}</strong> : part))}</>;
}
